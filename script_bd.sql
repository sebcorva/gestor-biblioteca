DROP TABLE IF EXISTS libros CASCADE CONSTRAINTS;

-- 2. Creación de la tabla 'libros'
-- Mapeada a la entidad com.duoc.gestor_biblioteca.model.Libro
CREATE TABLE libros (
    id                NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    titulo            VARCHAR2(255) NOT NULL,
    autor             VARCHAR2(255) NOT NULL,
    anio_publicacion  NUMBER(4)     NOT NULL,
    genero            VARCHAR2(100) NOT NULL
);

