-- ---------------------------------------------------------------------
-- Limpieza (re-ejecutable). Primero la tabla hija por la FK.
-- La tabla "libros" corresponde a la version anterior del proyecto (CRUD de libros).
-- ---------------------------------------------------------------------
DROP TABLE IF EXISTS comentarios CASCADE CONSTRAINTS;
DROP TABLE IF EXISTS publicaciones CASCADE CONSTRAINTS;
DROP TABLE IF EXISTS libros CASCADE CONSTRAINTS;

-- ---------------------------------------------------------------------
-- DDL (Hibernate lo crea solo con ddl-auto=update; se deja como referencia)
-- ---------------------------------------------------------------------

-- Publicacion: recomendacion de un libro hecha por un usuario premium o ADMIN.
-- usuario_id no tiene FK: el usuario vive en otro microservicio (esquema USUARIOS_APP).
CREATE TABLE publicaciones (
    id_publicacion          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    titulo                  VARCHAR2(100)  NOT NULL,
    autor                   VARCHAR2(100)  NOT NULL,
    anio_publicacion_libro  VARCHAR2(4)    NOT NULL,
    genero                  VARCHAR2(50)   NOT NULL,
    resena                  VARCHAR2(1000) NOT NULL,
    fecha_publicacion       TIMESTAMP(6)   NOT NULL,
    usuario_id              NUMBER         NOT NULL,
    usuario_nombre          VARCHAR2(100)  NOT NULL,
    CONSTRAINT pk_publicaciones PRIMARY KEY (id_publicacion),
    CONSTRAINT ck_publicaciones_genero CHECK (genero IN (
        'FICCION', 'FANTASIA', 'CIENCIA_FICCION', 'MISTERIO', 'THRILLER', 'ROMANCE', 'HISTORICO',
        'BIOGRAFIA', 'AUTOAYUDA', 'TECNOLOGIA', 'EDUCACION', 'FILOSOFIA', 'POESIA', 'TERROR'))
);

-- Comentario: pertenece a una publicacion (relacion 1:N).
-- Al eliminar una publicacion, JPA elimina sus comentarios (cascade + orphanRemoval en la entidad).
CREATE TABLE comentarios (
    id_comentario   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    publicacion_id  NUMBER        NOT NULL,
    contenido       VARCHAR2(500) NOT NULL,
    usuario_id      NUMBER        NOT NULL,
    usuario_nombre  VARCHAR2(100) NOT NULL,
    fecha           TIMESTAMP(6)  NOT NULL,
    CONSTRAINT pk_comentarios PRIMARY KEY (id_comentario),
    CONSTRAINT fk_comentarios_publicacion FOREIGN KEY (publicacion_id)
        REFERENCES publicaciones (id_publicacion)
);

-- Indice para listar rapido los comentarios de una publicacion (GET /publicaciones/{id}/comentarios)
CREATE INDEX ix_comentarios_publicacion ON comentarios (publicacion_id);

